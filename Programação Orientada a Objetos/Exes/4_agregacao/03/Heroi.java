
public class Heroi {
    private String nome;
    private String classeRPG;

    public Heroi(String nome, String classeRPG) {
        this.nome = nome;
        this.classeRPG = classeRPG;
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public String getClasseRPG() {
        return classeRPG;
    }

    public void setClasseRPG(String classeRPG) {
        this.classeRPG = classeRPG;
    }
}
