
public class ProjetoInovacao {
    private String titulo;
    private double orcamento;

    public ProjetoInovacao(String titulo, double orcamento) {
        this.titulo = titulo;
        this.orcamento = orcamento;
    }
    
    public String getTitulo() {
        return titulo;
    }

    public double getOrcamento() {
        return orcamento;
    }
}
